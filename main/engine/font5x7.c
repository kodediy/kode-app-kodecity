int font5x7_index(char ch)
{
    if ( ' ' == ch )
    {
        return 0;
    }
    if ( ('A' <= ch) && ('Z' >= ch) )
    {
        return 1 + (ch - 'A');
    }
    if ( '!' == ch )
    {
        return 27;
    }
    if ( '>' == ch )
    {
        return 28;
    }
    if ( '.' == ch )
    {
        return 29;
    }
    if ( ('a' <= ch) && ('z' >= ch) )
    {
        return 30 + (ch - 'a');
    }
    if ( ('0' <= ch) && ('9' >= ch) )
    {
        return 56 + (ch - '0');
    }
    switch ( ch )
    {
        case '-': return 66;
        case ':': return 67;
        case '/': return 68;
        case '_': return 69;
        case '?': return 70;
        case ',': return 71;
        case '\'': return 72;
        case '(': return 73;
        case ')': return 74;
        case '+': return 75;
        default: return 0;
    }
}
